// Builds src/vendor-manifest.ts: the third-party browser files the relay may serve under
// /vendor/, each pinned to an exact npm version and its SHA-384. The relay fetches a file
// from a public npm mirror the first time it's asked for, checks the hash, and only then
// serves (and caches) it from rclicker's own origin. See src/vendor.ts.
//
// Usage (from relay/): node scripts/vendor-manifest.mjs
// To upgrade a library, change its version below, run this, and commit both files.

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdtempSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, relative } from 'node:path';

const PACKAGES = [
  {
    name: 'pdfjs-dist',
    version: '6.4.299',
    prefix: '/vendor/pdfjs/',
    include: [
      // The "legacy" build supports older browsers (company PCs often lag behind).
      /^legacy\/build\/pdf(\.worker)?\.min\.mjs$/,
      /^wasm\/(jbig2|openjpeg|qcms_bg)\.wasm$/,
      /^wasm\/(jbig2|openjpeg)_nowasm_fallback\.js$/,
      /^standard_fonts\//,
      /^cmaps\//,
      /^iccs\//,
      /^LICENSE$/,
    ],
  },
  {
    name: 'qrcode-generator',
    version: '2.0.4',
    prefix: '/vendor/qrcode/',
    include: [/^dist\/qrcode\.mjs$/],
  },
];

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

const entries = [];
const work = mkdtempSync(join(tmpdir(), 'rclicker-vendor-'));
try {
  for (const pkg of PACKAGES) {
    const spec = `${pkg.name}@${pkg.version}`;
    const tgz = execFileSync('npm', ['pack', spec, '--silent', '--pack-destination', work], { encoding: 'utf8' }).trim().split('\n').pop();
    const dir = join(work, pkg.name);
    execFileSync('mkdir', ['-p', dir]);
    execFileSync('tar', ['xzf', join(work, tgz), '-C', dir]);
    const root = join(dir, 'package');
    for (const file of walk(root).map((p) => relative(root, p).split('\\').join('/')).sort()) {
      if (!pkg.include.some((re) => re.test(file))) continue;
      const sha384 = createHash('sha384').update(readFileSync(join(root, file))).digest('base64');
      entries.push([pkg.prefix + file, `${spec}/${file}`, sha384]);
    }
  }
} finally {
  rmSync(work, { recursive: true, force: true });
}

const lines = entries.map(([path, source, hash]) => `  ${JSON.stringify(path)}: [${JSON.stringify(source)}, ${JSON.stringify(hash)}],`);
writeFileSync(
  new URL('../src/vendor-manifest.ts', import.meta.url),
  `// Generated by scripts/vendor-manifest.mjs. Do not edit by hand.\n` +
    `// Path served by the relay -> [npm "package@version/file", SHA-384 (base64)].\n` +
    `export const VENDOR_FILES: Readonly<Record<string, readonly [source: string, sha384: string]>> = {\n${lines.join('\n')}\n};\n`,
);
console.log(`Wrote ${entries.length} entries.`);
